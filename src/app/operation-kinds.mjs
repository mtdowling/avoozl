const INCIDENT = new Set(["jobs.stop"]);

export function classifyOperation(name) {
  if (typeof name !== "string" || !name) return null;
  if (name.startsWith("safety.")) return "incident";
  if (INCIDENT.has(name)) return "incident";
  if (OBSERVE.has(name)) return "observe";
  if (DRAFT.has(name)) return "draft";
  if (EXECUTE.has(name)) return "execute";
  if (PROTECT.has(name)) return "protect";
  return null;
}
