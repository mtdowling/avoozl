// `npm run format:check` must reach every JS/TS-family, JSON and CSS file in
// the repository, wherever it lives. Only the paths below may be left out.
import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const FAMILY = /\.(js|mjs|cjs|ts|mts|cts|tsx|jsx|json|jsonc|css)$/;
const EXCLUDED = [
  /^docs\/(research|evidence)\//, // records of what was observed at the time
  /(^|\/)node_modules\//,
  /^kirocrew-app\/ui\/dist\//, // built output
  /^kirocrew-app\/bin\/lib\//, // built output
  /^scripts\/test\/test-map\.json$/, // generated
  /^kirocrew-app\/agents\/[^/]+\.json$/, // generated by npm run build:agents
  /^package-lock\.json$/, // generated by npm
];

test("format:check runs Biome on the whole repository", () => {
  const { scripts } = JSON.parse(
    fs.readFileSync(path.join(root, "package.json"), "utf8"),
  );
  // No path arguments: biome.json's files.includes decides the scope.
  assert.equal(scripts["format:check"], "biome format");
  assert.equal(scripts.format, "biome format --write");
});

test("format:check covers every JS/TS-family file outside the exclusions", () => {
  const tracked = execFileSync("git", ["ls-files", "-z"], {
    cwd: root,
    encoding: "utf8",
  })
    .split("\0")
    .filter(
      (name) => FAMILY.test(name) && !EXCLUDED.some((re) => re.test(name)),
    );
  const run = spawnSync(
    process.execPath,
    [
      path.join(root, "node_modules/@biomejs/biome/bin/biome"),
      "format",
      "--verbose",
      "--max-diagnostics=0",
      "--colors=off",
    ],
    { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
  );
  const out = run.stdout + run.stderr,
    start = out.indexOf("Files processed:");
  assert.ok(start >= 0, out.slice(0, 2000));
  const processed = new Set();
  for (const line of out.slice(start).split(/\r?\n/).slice(1)) {
    const match = /^\s+- (.+)$/.exec(line);
    if (match) processed.add(match[1].trim().replaceAll("\\", "/"));
    else if (line.trim() && processed.size) break;
  }
  assert.ok(tracked.length > 100, `only ${tracked.length} tracked files`);
  assert.deepEqual(
    tracked.filter((name) => !processed.has(name)),
    [],
  );
});
